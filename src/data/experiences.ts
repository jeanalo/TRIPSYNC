// Helper to get experiences for a specific country
export function getExperiencesByCountry(country: string) {
  return EXPERIENCES.filter((exp) => exp.country.toLowerCase() === country.toLowerCase());
}

// Helper to get a single experience by id
export function getExperienceById(id: number) {
  return EXPERIENCES.find((exp) => exp.id === id);
}

// Get list of all countries that have experiences
export function getAvailableCountries() {
  return [...new Set(EXPERIENCES.map((exp) => exp.country))].sort();
}
